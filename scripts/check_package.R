local({
 candidates<-vapply(sys.frames(),function(e)if(is.null(e$ofile))'' else as.character(e$ofile)[1],character(1))
 candidates<-candidates[nzchar(candidates)]
 if(!length(candidates))stop('Run this entry point with source(path/to/check_package.R).')
 pkg<-dirname(dirname(normalizePath(tail(candidates,1),winslash='/',mustWork=TRUE)))
 base<-dirname(pkg)
 if(!requireNamespace('knitr',quietly=TRUE)||!requireNamespace('rmarkdown',quietly=TRUE))stop('Install knitr and rmarkdown to build the English vignette.')
 if(!rmarkdown::pandoc_available())stop('Pandoc is required; run from RStudio or configure Pandoc before building.')
 if(!file.exists(file.path(pkg,'DESCRIPTION')))stop('Package source not found: ',pkg)
 out<-tempfile('check_SPADES_IND_018_',tmpdir=base);dir.create(out)
 wd<-getwd();on.exit(setwd(wd),add=TRUE);setwd(out)
 exe<-file.path(R.home('bin'),if(.Platform$OS.type=='windows')'R.exe' else 'R')
 cat('BUILD | source package including English vignette; output: ',out,'\n',sep='');flush.console()
 buildlog<-file.path(out,'build.log')
 status<-system2(exe,c('CMD','build','--no-manual',shQuote(pkg)),stdout=buildlog,stderr=buildlog)
 if(status!=0L) {cat(readLines(buildlog,warn=FALSE),sep='\n');stop('R CMD build failed. Report: ',out)}
 archive<-file.path(out,'SPADES.IND_0.1.8.tar.gz')
 if(!file.exists(archive))stop('Built archive missing. Inspect: ',buildlog)
 cat('CHECK | PDF manual: ',if(isTRUE(getOption('SPADES.check_manual',FALSE)))'enabled' else 'omitted (set SPADES.check_manual=TRUE with TeX installed)', '; unavailable suggested packages not forced. See check.log for progress.\n',sep='');flush.console()
 old<-Sys.getenv('_R_CHECK_FORCE_SUGGESTS_',unset=NA_character_)
 on.exit({if(is.na(old))Sys.unsetenv('_R_CHECK_FORCE_SUGGESTS_') else Sys.setenv('_R_CHECK_FORCE_SUGGESTS_'=old)},add=TRUE)
 Sys.setenv('_R_CHECK_FORCE_SUGGESTS_'='false')
 checklog<-file.path(out,'check.log')
 check_args<-c('CMD','check',if(!isTRUE(getOption('SPADES.check_manual',FALSE)))'--no-manual',shQuote(archive))
 status<-system2(exe,check_args,stdout=checklog,stderr=checklog)
 report<-file.path(out,'SPADES.IND.Rcheck','00check.log')
 lines<-readLines(if(file.exists(report))report else checklog,warn=FALSE)
 starts<-grep('^\\* checking .* (NOTE|WARNING|ERROR)$',lines)
 keep<-tail(seq_along(lines),12L)
 for(i in starts) {
   next_section<-which(seq_along(lines)>i & grepl('^\\*',lines))
   last<-if(length(next_section))next_section[1L]-1L else length(lines)
   keep<-c(keep,seq.int(i,last))
 }
 cat(lines[sort(unique(keep))],sep='\n')
 cat('\nR CMD check exit status: ',status,'\nReport directory: ',out,'\n',sep='')
 cat('This is a development check, not a CRAN certification. Review ERROR/WARNING/NOTE entries.\n')
 if(status!=0L)stop('R CMD check failed. Inspect the report above before continuing.')
})
